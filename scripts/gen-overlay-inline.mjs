// 生成 src/chat/overlay-inline.ts：把 overlay 入口需要的 CSS 内联、脚本路径固定下来，
// 供「胶囊 → 动态悬浮窗」在运行时拼出可用 HTML。
//
// 为什么需要：
//   overlay.create 的动态悬浮窗由主窗口以 blob: 加载，相对 URL 会相对主窗口解析；
//   启动器 overlayHtml() 又会把 <link rel=stylesheet> 抽到外层 head（那里只有主窗口 <base>）。
//   因此必须：CSS 内联为 <style>、脚本 src 用绝对地址。产物哈希无法在源码里写死，
//   故由本脚本在构建后读取真实产物、生成内联模块（再跑一次构建让它进入 bundle）。
//
// 用法（见 package.json build）：
//   vite build && node scripts/gen-overlay-inline.mjs && vite build
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const distDir = resolve(root, 'dist')
const overlayHtmlPath = resolve(distDir, 'overlay.html')
const outPath = resolve(root, 'src/chat/overlay-inline.ts')

function fail(msg) {
  console.error('[gen-overlay-inline] ' + msg)
  process.exit(1)
}

if (!existsSync(overlayHtmlPath)) fail('未找到 dist/overlay.html，请先 vite build')
const html = readFileSync(overlayHtmlPath, 'utf8')

// 1) 脚本入口（entryFileNames 固定为 assets/<name>.js）
const scriptMatch = /<script[^>]*\bsrc\s*=\s*["']([^"']*overlay\.js)["'][^>]*>/i.exec(html)
if (!scriptMatch) fail('未在 dist/overlay.html 找到 overlay.js 脚本引用')
const scriptRel = scriptMatch[1].replace(/^\.\//, '')

// 2) 样式（读取被引用的 CSS 文件内容并内联）
let css = ''
const linkMatches = [...html.matchAll(/<link[^>]+rel=["']stylesheet["'][^>]*href=["']([^"']+)["'][^>]*>/gi)]
if (linkMatches.length === 0) {
  const alt = [...html.matchAll(/<link[^>]+href=["']([^"']+\.css)["'][^>]*>/gi)]
  linkMatches.push(...alt)
}
for (const m of linkMatches) {
  const rel = m[1].replace(/^\.\//, '')
  const cssPath = resolve(distDir, rel)
  if (!existsSync(cssPath)) {
    console.warn('[gen-overlay-inline] 跳过缺失样式: ' + rel)
    continue
  }
  css += readFileSync(cssPath, 'utf8')
}
if (!css) fail('未能从产物中取得任何 CSS，放弃生成（将退化为运行时拉取）')

const module = `// AUTO-GENERATED by scripts/gen-overlay-inline.mjs — 请勿手改，勿提交（见 .gitignore）。
export const OVERLAY_SCRIPT_REL = ${JSON.stringify(scriptRel)}
export const OVERLAY_CSS = ${JSON.stringify(css)}

export function buildOverlayPayload(base: string): { html: string; scriptAbs: string } {
  const root = String(base || '').replace(/\\/+$/, '')
  const scriptAbs = root + '/dist/' + OVERLAY_SCRIPT_REL
  const html =
    '<style>' + OVERLAY_CSS + '</style>' +
    '<div id="root"></div>' +
    '<script type="module" crossorigin src="' + scriptAbs + '"></script>'
  return { html, scriptAbs }
}
`

writeFileSync(outPath, module, 'utf8')
console.log(`[gen-overlay-inline] 已生成 ${outPath.replace(root, '.')}（css ${css.length} 字节, script ${scriptRel}）`)
